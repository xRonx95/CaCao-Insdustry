// Regenerate after adding/changing public application files. Never include SQL or secrets.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const files=[];
function walk(folder){for(const entry of fs.readdirSync(path.join(root,folder),{withFileTypes:true})){const file=folder+'/'+entry.name;if(entry.isDirectory())walk(file);else files.push(file);}}
for(const folder of ['assets/css','assets/js','images','admin','farmer','field'])walk(folder);
if(fs.existsSync(path.join(root,'assets/vendor')))walk('assets/vendor');
files.push(...fs.readdirSync(root).filter(file=>file.endsWith('.html')),'favicon.ico');
const libraries=new Set();
for(const file of files.filter(file=>file.endsWith('.html'))){for(const match of fs.readFileSync(path.join(root,file),'utf8').matchAll(/(?:src|href)="(https:\/\/[^\"]+)"/g))if(/\.(js|css)(\?|$)/.test(match[1]))libraries.add(match[1]);}
for(const file of ['layers.png','layers-2x.png','marker-icon.png','marker-icon-2x.png','marker-shadow.png'])libraries.add('https://unpkg.com/leaflet@1.9.4/dist/images/'+file);
const version=crypto.createHash('sha256').update(files.map(file=>fs.readFileSync(path.join(root,file))).join('')).digest('hex').slice(0,12);
const worker=String.raw`// Generated by scripts/rebuild-offline-cache.cjs. Public files only; no API or tile caching.
const CACHE='cacao-shell-VERSION';
const ROOT=new URL('./',self.location.href);
const ASSETS=new Set(ASSET_LIST.map(path=>new URL(path,ROOT).href));
const LIBRARIES=LIBRARY_LIST;
const libraryImage=url=>url.startsWith('https://unpkg.com/leaflet@1.9.4/dist/images/')||url.startsWith('https://cdnjs.cloudflare.com/ajax/libs/leaflet.draw/1.0.4/images/');
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll([...ASSETS])).then(()=>self.skipWaiting())));
self.addEventListener('activate',event=>event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(key=>key.startsWith('cacao-shell-')&&key!==CACHE).map(key=>caches.delete(key)))).then(()=>self.clients.claim())));
self.addEventListener('fetch',event=>{
  if(event.request.method!=='GET')return;
  const parsed=new URL(event.request.url);
  const publicKey=parsed.origin===ROOT.origin&&parsed.pathname===ROOT.pathname?new URL('index.html',ROOT).href:new URL(parsed.pathname,parsed.origin).href;
  const publicFile=ASSETS.has(publicKey);
  const external=LIBRARIES.includes(parsed.href)||libraryImage(parsed.href)||(parsed.origin==='https://fonts.gstatic.com'&&event.request.destination==='font')||(parsed.origin==='https://fonts.googleapis.com'&&event.request.destination==='style');
  if(!publicFile&&!external)return;
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE),cacheKey=publicFile?publicKey:event.request;
    if(!self.navigator.onLine){const saved=await cache.match(cacheKey);if(saved)return saved;}
    try{
      const response=await fetch(event.request,{signal:AbortSignal.timeout(4000)});
      if(response.ok||response.type==='opaque')await cache.put(cacheKey,response.clone());
      return response;
    }catch(error){const saved=await cache.match(cacheKey);if(saved)return saved;throw error;}
  })());
});
self.addEventListener('message',event=>{
  if(event.data?.type!=='CACHE_LIBRARIES')return;
  event.waitUntil((async()=>{
    const cache=await caches.open(CACHE),failed=[];
    async function store(url,discover=false){
      try{
        const response=await fetch(url,{mode:'cors',credentials:'omit',signal:AbortSignal.timeout(15000)});
        if(!response.ok)throw new Error();
        if(discover){const css=await response.clone().text();const dependencies=[...css.matchAll(/url\(\s*['"]?([^'"\)\s]+)['"]?\s*\)/g)].map(match=>new URL(match[1],url).href).filter(libraryImage);await Promise.all(dependencies.map(dependency=>store(dependency)));}
        await cache.put(url,response);
      }catch{if(!await cache.match(url))failed.push(url);}
    }
    await Promise.all(LIBRARIES.map(url=>store(url,/\.css(\?|$)/.test(url))));
    event.ports[0]?.postMessage({ready:!failed.length,failed});
  })());
});
`.replace('VERSION',version).replace('ASSET_LIST',JSON.stringify(files)).replace('LIBRARY_LIST',JSON.stringify([...libraries]));
fs.writeFileSync(path.join(root,'service-worker.js'),worker);
console.log('Offline cache manifest: '+files.length+' public files; '+libraries.size+' dependency files.');
